-- Helper Function Keamanan Tenant
CREATE OR REPLACE FUNCTION get_user_cafe_id()
RETURNS BIGINT LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
    SELECT cafe_id FROM profiles WHERE id = auth.uid();
$$;

-- Policies Isolasi Tenant
CREATE POLICY "Staff can view store orders" ON orders
    FOR SELECT USING (
        store_id IN (SELECT id FROM stores WHERE cafe_id = get_user_cafe_id())
    );

CREATE POLICY "Cashiers can insert store orders" ON orders
    FOR INSERT WITH CHECK (
        store_id IN (SELECT id FROM stores WHERE cafe_id = get_user_cafe_id())
    );

-- 9. CHECKOUT ATOMIK (ZERO-TRUST PRICING, IDEMPOTENT)
-- Hardening: server-side pricing of variants and modifiers, per-store daily order numbers,
-- replay-safe on Idempotency-Key, executable by service_role only.
-- Per-store, per-day counter. One row lock serialises concurrent checkouts of
-- the same store and day, which is the intended throughput bound for one cafe.
CREATE TABLE IF NOT EXISTS order_counters (
    store_id   BIGINT NOT NULL REFERENCES stores(id) ON DELETE CASCADE,
    business_date DATE NOT NULL,
    last_value INTEGER NOT NULL DEFAULT 0,
    PRIMARY KEY (store_id, business_date)
);
ALTER TABLE order_counters ENABLE ROW LEVEL SECURITY;

CREATE OR REPLACE FUNCTION process_pos_checkout(
    p_store_id        BIGINT,
    p_shift_id        BIGINT,
    p_cashier_id      UUID,
    p_order_type      VARCHAR,
    p_customer_name   VARCHAR,
    p_table_number    VARCHAR,
    p_payment_method  VARCHAR,
    p_cash_received   INTEGER,
    p_payment_reference VARCHAR,
    p_discount_amount INTEGER,
    p_idempotency_key VARCHAR,
    p_items           JSONB
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_existing      RECORD;
    v_business_date DATE := (NOW() AT TIME ZONE 'Asia/Jakarta')::DATE;
    v_seq           INTEGER;
    v_order_id      BIGINT;
    v_order_no      TEXT;
    v_item          RECORD;
    v_product       RECORD;
    v_variant       RECORD;
    v_variant_name  VARCHAR(100);
    v_group         RECORD;
    v_group_count   INTEGER;
    v_mod_id        TEXT;
    v_mod           RECORD;
    v_order_item_id BIGINT;
    v_unit_price    INTEGER;
    v_unit_hpp      INTEGER;
    v_mod_price     INTEGER;
    v_mod_hpp       INTEGER;
    v_subtotal      INTEGER := 0;
    v_total_hpp     INTEGER := 0;
    v_total         INTEGER;
    v_change        INTEGER := 0;
    v_payment_id    BIGINT;
BEGIN
    IF p_payment_method NOT IN ('cash', 'qris', 'debit') THEN
        RAISE EXCEPTION 'Metode pembayaran tidak dikenal' USING ERRCODE = 'P0001';
    END IF;

    IF p_idempotency_key IS NULL OR length(p_idempotency_key) < 8 THEN
        RAISE EXCEPTION 'Idempotency key wajib diisi' USING ERRCODE = 'P0001';
    END IF;

    -- Replay of an already processed request returns the original result.
    SELECT o.id, o.order_no, o.total_amount, p.status, p.change_amount
      INTO v_existing
      FROM payments p JOIN orders o ON o.id = p.order_id
     WHERE p.idempotency_key = p_idempotency_key;
    IF FOUND THEN
        RETURN jsonb_build_object(
            'order_id', v_existing.id,
            'order_no', v_existing.order_no,
            'total_amount', v_existing.total_amount,
            'change_amount', COALESCE(v_existing.change_amount, 0),
            'payment_status', v_existing.status,
            'replayed', TRUE
        );
    END IF;

    IF NOT EXISTS (SELECT 1 FROM stores WHERE id = p_store_id) THEN
        RAISE EXCEPTION 'Toko tidak ditemukan' USING ERRCODE = 'P0001';
    END IF;

    IF p_shift_id IS NOT NULL AND NOT EXISTS (
        SELECT 1 FROM shifts
         WHERE id = p_shift_id AND store_id = p_store_id AND status = 'open'
    ) THEN
        RAISE EXCEPTION 'Shift tidak aktif atau bukan milik toko ini' USING ERRCODE = 'P0001';
    END IF;

    IF p_items IS NULL OR jsonb_typeof(p_items) <> 'array' OR jsonb_array_length(p_items) = 0 THEN
        RAISE EXCEPTION 'Keranjang pesanan kosong' USING ERRCODE = 'P0001';
    END IF;

    INSERT INTO order_counters (store_id, business_date, last_value)
    VALUES (p_store_id, v_business_date, 1)
    ON CONFLICT (store_id, business_date)
    DO UPDATE SET last_value = order_counters.last_value + 1
    RETURNING last_value INTO v_seq;

    v_order_no := 'TRX-' || to_char(v_business_date, 'YYYYMMDD') || '-' || LPAD(v_seq::TEXT, 4, '0');

    INSERT INTO orders (store_id, shift_id, order_no, order_type, customer_name,
                        table_number, status, created_by)
    VALUES (p_store_id, p_shift_id, v_order_no, p_order_type, p_customer_name,
            p_table_number, 'pending_payment', p_cashier_id)
    RETURNING id INTO v_order_id;

    FOR v_item IN
        SELECT * FROM jsonb_to_recordset(p_items)
            AS x(product_id BIGINT, variant_id BIGINT, quantity INT, notes TEXT, modifiers JSONB)
    LOOP
        IF v_item.quantity IS NULL OR v_item.quantity < 1 OR v_item.quantity > 99 THEN
            RAISE EXCEPTION 'Jumlah item harus antara 1 dan 99' USING ERRCODE = 'P0001';
        END IF;

        SELECT id, name, base_price, base_hpp INTO v_product
          FROM products
         WHERE id = v_item.product_id AND store_id = p_store_id AND is_active;
        IF NOT FOUND THEN
            RAISE EXCEPTION 'Produk tidak ditemukan atau tidak aktif' USING ERRCODE = 'P0001';
        END IF;

        v_unit_price := v_product.base_price;
        v_unit_hpp   := v_product.base_hpp;
        v_variant_name := NULL;

        IF v_item.variant_id IS NOT NULL THEN
            SELECT id, name, price_adjustment, hpp_adjustment INTO v_variant
              FROM product_variants
             WHERE id = v_item.variant_id AND product_id = v_product.id AND is_active;
            IF NOT FOUND THEN
                RAISE EXCEPTION 'Varian tidak valid untuk produk %', v_product.name USING ERRCODE = 'P0001';
            END IF;
            v_unit_price := v_unit_price + v_variant.price_adjustment;
            v_unit_hpp   := v_unit_hpp   + v_variant.hpp_adjustment;
            v_variant_name := v_variant.name;
        END IF;

        INSERT INTO order_items (order_id, product_id, variant_id, product_name, variant_name,
                                 unit_price, unit_hpp, quantity, subtotal, notes)
        VALUES (v_order_id, v_product.id, v_item.variant_id, v_product.name, v_variant_name,
                v_unit_price, v_unit_hpp, v_item.quantity, 0, v_item.notes)
        RETURNING id INTO v_order_item_id;

        v_mod_price := 0;
        v_mod_hpp   := 0;
        IF v_item.modifiers IS NOT NULL AND jsonb_typeof(v_item.modifiers) = 'array' THEN
            FOR v_mod_id IN SELECT jsonb_array_elements_text(v_item.modifiers) LOOP
                SELECT mo.id, mo.name, mo.price_adjustment, mo.hpp_adjustment INTO v_mod
                  FROM modifier_options mo
                  JOIN modifier_groups mg ON mg.id = mo.group_id
                  JOIN product_modifier_groups pmg ON pmg.modifier_group_id = mg.id
                 WHERE mo.id = v_mod_id::BIGINT
                   AND mg.store_id = p_store_id
                   AND pmg.product_id = v_product.id;
                IF NOT FOUND THEN
                    RAISE EXCEPTION 'Modifier tidak valid untuk produk %', v_product.name USING ERRCODE = 'P0001';
                END IF;

                IF EXISTS (SELECT 1 FROM order_item_modifiers
                            WHERE order_item_id = v_order_item_id AND modifier_option_id = v_mod.id) THEN
                    RAISE EXCEPTION 'Modifier % dipilih lebih dari sekali', v_mod.name USING ERRCODE = 'P0001';
                END IF;

                INSERT INTO order_item_modifiers (order_item_id, modifier_option_id, modifier_name,
                                                  unit_price, unit_hpp)
                VALUES (v_order_item_id, v_mod.id, v_mod.name, v_mod.price_adjustment, v_mod.hpp_adjustment);

                v_mod_price := v_mod_price + v_mod.price_adjustment;
                v_mod_hpp   := v_mod_hpp   + v_mod.hpp_adjustment;
            END LOOP;
        END IF;

        -- Every modifier group linked to the product constrains the selection:
        -- required groups need at least one option, none may exceed max_selection.
        FOR v_group IN
            SELECT mg.id, mg.name, mg.is_required, mg.min_selection, mg.max_selection
              FROM product_modifier_groups pmg
              JOIN modifier_groups mg ON mg.id = pmg.modifier_group_id
             WHERE pmg.product_id = v_product.id
        LOOP
            SELECT count(*) INTO v_group_count
              FROM order_item_modifiers oim
              JOIN modifier_options mo ON mo.id = oim.modifier_option_id
             WHERE oim.order_item_id = v_order_item_id AND mo.group_id = v_group.id;

            IF v_group_count > v_group.max_selection
               OR v_group_count < GREATEST(v_group.min_selection, CASE WHEN v_group.is_required THEN 1 ELSE 0 END) THEN
                RAISE EXCEPTION 'Pilihan "%" untuk % tidak sesuai aturan (min %, maks %)',
                    v_group.name, v_product.name,
                    GREATEST(v_group.min_selection, CASE WHEN v_group.is_required THEN 1 ELSE 0 END),
                    v_group.max_selection USING ERRCODE = 'P0001';
            END IF;
        END LOOP;

        UPDATE order_items
           SET unit_price = v_unit_price + v_mod_price,
               unit_hpp   = v_unit_hpp   + v_mod_hpp,
               subtotal   = (v_unit_price + v_mod_price) * v_item.quantity
         WHERE id = v_order_item_id;

        v_subtotal  := v_subtotal  + (v_unit_price + v_mod_price) * v_item.quantity;
        v_total_hpp := v_total_hpp + (v_unit_hpp   + v_mod_hpp)   * v_item.quantity;
    END LOOP;

    IF p_discount_amount < 0 OR p_discount_amount > v_subtotal THEN
        RAISE EXCEPTION 'Diskon melebihi subtotal' USING ERRCODE = 'P0001';
    END IF;
    v_total := v_subtotal - p_discount_amount;
    IF v_total <= 0 THEN
        RAISE EXCEPTION 'Total pesanan harus lebih dari nol' USING ERRCODE = 'P0001';
    END IF;

    UPDATE orders
       SET subtotal_amount = v_subtotal,
           discount_amount = p_discount_amount,
           total_amount = v_total,
           total_hpp_snapshot = v_total_hpp
     WHERE id = v_order_id;

    IF p_payment_method = 'cash' THEN
        IF p_cash_received < v_total THEN
            RAISE EXCEPTION 'Uang tunai kurang dari total belanja' USING ERRCODE = 'P0001';
        END IF;
        v_change := p_cash_received - v_total;
    END IF;

    -- QRIS and debit have no gateway yet: the cashier confirms receipt against the customer's
    -- proof of payment, so the payment is recorded as succeeded together with who-said-so
    -- evidence (manual_reference and an append-only payment_events row).
    INSERT INTO payments (order_id, payment_method, amount, status, cash_received, change_amount,
                          manual_reference, idempotency_key)
    VALUES (v_order_id, p_payment_method, v_total, 'succeeded',
            CASE WHEN p_payment_method = 'cash' THEN p_cash_received END,
            CASE WHEN p_payment_method = 'cash' THEN v_change END,
            NULLIF(btrim(p_payment_reference), ''), p_idempotency_key)
    RETURNING id INTO v_payment_id;

    IF p_payment_method <> 'cash' THEN
        INSERT INTO payment_events (payment_id, event_type, payload)
        VALUES (v_payment_id, 'manual_confirmed',
                jsonb_build_object('method', p_payment_method,
                                   'reference', NULLIF(btrim(p_payment_reference), ''),
                                   'amount', v_total));
    END IF;

    UPDATE orders SET status = 'confirmed', updated_at = NOW() WHERE id = v_order_id;

    INSERT INTO kitchen_tickets (order_id, store_id, ticket_no, status)
    VALUES (v_order_id, p_store_id, v_order_no, 'new');

    RETURN jsonb_build_object(
        'order_id', v_order_id,
        'order_no', v_order_no,
        'subtotal_amount', v_subtotal,
        'discount_amount', p_discount_amount,
        'total_amount', v_total,
        'change_amount', v_change,
        'payment_status', 'succeeded',
        'replayed', FALSE
    );
END;
$$;

-- The function runs as its owner and trusts p_cashier_id, so only the server
-- (service role) may call it; anon and authenticated clients must not.
REVOKE ALL ON FUNCTION process_pos_checkout(
    BIGINT, BIGINT, UUID, VARCHAR, VARCHAR, VARCHAR, VARCHAR, INTEGER, VARCHAR, INTEGER, VARCHAR, JSONB
) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION process_pos_checkout(
    BIGINT, BIGINT, UUID, VARCHAR, VARCHAR, VARCHAR, VARCHAR, INTEGER, VARCHAR, INTEGER, VARCHAR, JSONB
) TO service_role;
